    public static Localizer Instance { get; } = new();
    private string _language = "id";
    public string Language => _language;
    public CultureInfo Culture => CultureInfo.GetCultureInfo(_language == "en" ? "en-US" : "id-ID");
    public string this[string key] => _language == "en" && English.TryGetValue(key, out var value) ? value : key;
    public static string Text(string key) => Instance[key];
    public static string Format(string key, params object[] args) => string.Format(Instance.Culture, Text(key), args);
    public event PropertyChangedEventHandler? PropertyChanged;
    public event Action? Changed;
    public void SetLanguage(string? language)
    {
        var value = language == "en" ? "en" : "id";
        if (_language == value) return;
        _language = value;
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs("Item[]"));
        Changed?.Invoke();
    }
